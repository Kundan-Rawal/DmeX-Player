"""Generate fixed-zone measured HRIR banks. Build-time deps: h5py, numpy, scipy."""
from pathlib import Path
import hashlib
import math
import textwrap
import h5py
import numpy as np
from scipy.signal import resample_poly

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "music-player-ui/src-tauri/resources/hrtf/subject_003.sofa"
OUTPUT = ROOT / "audio-engine-cpp/PortableHrtfData.h"
DIRECTIONS = [(-45, 0), (45, 0), (-90, 0), (90, 0), (-145, 0), (145, 0), (-48, 45), (48, 45)]
RATES = [22050, 32000, 44100, 48000, 88200, 96000]

def unit(azimuth, elevation):
    az, el = np.radians(azimuth), np.radians(elevation)
    return np.stack([np.cos(el) * np.cos(az), np.cos(el) * np.sin(az), np.sin(el)], axis=-1)

def main():
    with h5py.File(SOURCE, "r") as source:
        rate = int(source["Data.SamplingRate"][0])
        ir = source["Data.IR"][:]
        positions = source["SourcePosition"][:]
        assert np.all(source["Data.Delay"][:] == 0), "Nonzero SOFA delays need explicit preservation"
        assert positions.shape[1] == 3 and ir.shape[1] == 2
        assert source["ReceiverPosition"][0, 1, 0] > 0, "First SOFA receiver must be the left ear"
        license_text = source.attrs["License"].decode()
    vectors = unit(positions[:, 0], positions[:, 1])
    selected = []
    for az, el in DIRECTIONS:
        # DmeX uses negative azimuth for left; SOFA uses positive for left.
        index = int(np.argmax(vectors @ unit(-az, el)))
        pair = ir[index].copy()
        pair /= np.sqrt(np.sum(pair * pair) / 2.0)
        selected.append(pair)
        print(f"Zone {az:+4}/{el:2}: measurement {index}, SOFA {positions[index, :2]}")
    selected = np.asarray(selected)
    lines = ["#pragma once", "// Generated by scripts/generate_portable_hrtf.py; do not edit.",
             "// CIPIC subject_003. Original permission notice follows:"]
    lines += ["// " + line for line in textwrap.wrap(license_text, 100)]
    lines += [f"// Source SHA256: {hashlib.sha256(SOURCE.read_bytes()).hexdigest()}",
              "namespace dmex_hrtf {", "inline constexpr int kDirectionCount = 8;",
              "inline constexpr float azimuth[] = {" + ",".join(str(v[0]) for v in DIRECTIONS) + "};",
              "inline constexpr float elevation[] = {" + ",".join(str(v[1]) for v in DIRECTIONS) + "};"]
    entries = []
    for target in RATES:
        gcd = math.gcd(rate, target)
        bank = resample_poly(selected, target // gcd, rate // gcd, axis=-1).astype(np.float32)
        # Discrete-time convolution needs sample-rate gain compensation.
        bank *= rate / target
        taps = bank.shape[-1]
        lines.append(f"inline constexpr float bank{target}[8][2][{taps}] = {{")
        for pair in bank:
            lines.append("{")
            for ear in pair:
                values = [f"{float(value):.9e}f" for value in ear]
                lines += ["{" + ",".join(values) + "},"]
            lines.append("},")
        lines.append("};")
        entries.append(f"{{{target},{taps},&bank{target}[0][0][0]}}")
    lines += ["struct Bank { int rate, taps; const float* data; };",
              "inline constexpr Bank banks[] = {" + ",".join(entries) + "};", "}", ""]
    OUTPUT.write_text("\n".join(lines), encoding="ascii")
    print(f"Generated {OUTPUT.name}: {OUTPUT.stat().st_size} bytes")

if __name__ == "__main__":
    main()
